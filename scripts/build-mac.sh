#!/bin/bash
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
bash "$root/scripts/fetch-sparkle.sh"
bash "$root/scripts/build-speech.sh"
out="${1:-$root/build}/Tasktap.app"
contents="$out/Contents"
mkdir -p "$contents/MacOS" "$contents/Resources/prototype/assets"
# Retire bundled worker adapters when updating an existing build.
rm -f "$contents/Resources/codex_plan.py" "$contents/Resources/agy_session.py"
cp "$root/scripts/workspace_terminal.py" "$contents/Resources/"
ditto "$root/prototype" "$contents/Resources/prototype"
cp "$root/LICENSE" "$contents/Resources/"
cp "$root/build/tasktap-speech" "$contents/Resources/"
ditto "$root/build/speech-runtime-resources" "$contents/Resources"
ditto "$root/build/speech-notices" "$contents/Resources/Speech-Licenses"
cp "$root/build/sparkle/LICENSE" "$contents/Resources/Sparkle-LICENSE"
cp "$root/native/Info.plist" "$contents/Info.plist"
cp "$root/scripts/claude_desktop.py" "$root/scripts/session_activity.py" "$root/scripts/project_sessions.py" "$root/scripts/visible_session.py" "$root/scripts/session_lifecycle.py" "$root/scripts/terminal_hosts.py" "$root/scripts/extra_terminals.py" "$root/scripts/cmux_host.py" "$root/scripts/router-provider" "$root/scripts/worker_usage.py" "$root/scripts/plan_usage.py" "$root/scripts/PROVIDER-NOTICES" "$root/scripts/ask-user" "$root/scripts/agent-tools" "$root/scripts/run-agent" "$root/scripts/cmux-sessions" "$root/scripts/cmux_sessions.py" "$root/scripts/desktop_sessions.py" "$root/scripts/kokoro-voice" "$root/scripts/session_models.py" "$contents/Resources/"
cp "$root/prototype/assets/resonator/Tasktap.icns" "$contents/Resources/"
mkdir -p "$contents/Frameworks"
ditto "$root/build/sparkle/Sparkle.framework" "$contents/Frameworks/Sparkle.framework"
swiftc -F "$contents/Frameworks" -framework Sparkle -Xlinker -rpath -Xlinker @executable_path/../Frameworks -O -target "$(uname -m)-apple-macosx26.0" -module-cache-path "${TMPDIR:-/tmp}/workspace-assistant-module-cache" "$root"/native/*.swift -o "$contents/MacOS/Tasktap"
swiftc -O "$root/scripts/plan-credentials.swift" -o "$contents/Resources/plan-credentials"
codesign --force --sign - "$contents/Resources/plan-credentials"
codesign --force --sign - "$contents/Resources/tasktap-speech"
codesign --force --sign - --identifier io.github.harzerheribert.tasktap "$out"
codesign --verify --strict "$out"
printf '%s\n' "$out"
