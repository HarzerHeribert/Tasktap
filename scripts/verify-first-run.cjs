    assert.match(await page.locator('#modal').innerText(),/Fixture result with file locations/);
    await click('Close dialog');
    await cmd('open-app');
    assert.equal(await page.locator('.shell').isVisible(),true);
    await page.setViewportSize({width:960,height:760});
    await click('Preferences');
    if(shots)await page.locator('#modal').screenshot({path:path.join(shots,'preferences.png')});
    await page.getByRole('navigation',{name:'Preferences categories'}).getByRole('button',{name:'Capture'}).click();
    await click('Reopen guided capture');
    await page.evaluate(folder=>projectsDiscovered([{folder,name:'tapped'}]),folder);
    await composer.fill('Explain this file.');await click('Review');
    const ref=await page.evaluate(()=>sent.findLast(m=>m.type==='context-resolve'));
    await page.evaluate(id=>captureContext.receive(id,{kind:'file',value:'/fixture/projects/tapped/test.swift',app:'Finder'}),ref.request);
    await page.getByRole('heading',{name:'Review new session'}).waitFor();
    await click('Close dialog');
    assert.equal(await composer.inputValue(),'Explain this file.');
    await composer.fill('');
    const talk=page.getByRole('button',{name:/Hold to talk/});
    await talk.focus();await page.keyboard.down('Space');
    const held=await page.evaluate(()=>recording.id);
    await page.evaluate(id=>{dictationEvent(id,'recording','');dictationEvent(id,'partial','What changed?')},held);
    assert.equal(await composer.inputValue(),'What changed?');
    await page.keyboard.up('Space');
    await page.evaluate(id=>dictationEvent(id,'text','What changed today?'),held);
    assert.equal(await composer.inputValue(),'What changed today?');
    assert.equal(await page.locator('#modal[open]').count(),0);
    await composer.fill('');
    await cmd('hw-capture');
    await page.waitForFunction(()=>recording?.owner==='shortcut');
    const recording=await page.evaluate(()=>sent.findLast(m=>m.type==='dictation-start').id);
    await page.evaluate(id=>dictationEvent(id,'recording',''),recording);
    await cmd('hw-capture-end');
    assert.equal(await page.evaluate(()=>sent.findLast(m=>m.type.startsWith('dictation-')).type),'dictation-finish');
    await page.evaluate(id=>dictationEvent(id,'text','Explain the tests.'),recording);
    assert.equal(await page.locator('#transcript').inputValue(),'Explain the tests.');
    await click('Review');
