    await page.goto(pathToFileURL(path.join(__dirname,'../prototype/index.html')).href);
    const cmd=action=>page.evaluate(action=>workspaceCommand(action),action);
    const click=name=>page.getByRole('button',{name,exact:true}).click();
    const shots=process.env.TASKTAP_SCREENSHOTS;
    await cmd('open-app');
    await page.evaluate(()=>projectsDiscovered([]));
