    await page.evaluate(r=>externalSessions([{...r,available:'no',state:'Closed'}]),owned);
    await cmd('home');
    assert.equal(await home.getByText('Result ready').count(),0);
    assert.equal(await home.getByText(follow.task,{exact:true}).count(),0);
    await page.evaluate(id=>workspaceCommand('notice-result',id),job.session);
