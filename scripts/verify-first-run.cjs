    await click('tapped');await click('ComfyUI');
    assert.equal(await composer.inputValue(),text);
    await click('ComfyUI');await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button',{name:'ComfyUI',exact:true}).isVisible(),true);
    await click('ComfyUI');await click('tapped');
    await composer.press('Meta+Enter');
    await page.getByRole('heading',{name:'Review new session'}).waitFor();
    assert.match(await page.locator('#modal').innerText(),/tapped/i);
    await cmd('open-app'); // Finder reopen should preserve the review.
    assert.equal(await page.evaluate(()=>sent.some(m=>m.type==='enqueue')),false);
    await click('Start session');
    const job=await page.evaluate(()=>sent.findLast(m=>m.type==='enqueue').job);
    assert.equal(job.mode,'ask');assert.equal(job.folder,folder);assert.equal(job.transcript,text);
    assert.equal(await page.evaluate(()=>sent.some(m=>['dictation-start','speak'].includes(m.type))),false);
    await page.evaluate(j=>acceptLive({capture:j.capture,folder:j.folder,name:'tapped',task:j.task}),job);
    assert.equal(await page.getByRole('button',{name:'Open in Terminal',exact:true}).count(),0);
    const receipt={session:job.session,capture:job.capture,mode:'ask',state:'Opened',delivery:'interactive',host:'terminal'};
    await page.evaluate(e=>agentReceipt(e),receipt);
    await home.getByRole('heading',{name:'Opening Claude Code'}).waitFor();
    assert.match(await home.innerText(),/If Claude asks whether you trust this folder/);
    assert.equal(await home.getByRole('button',{name:'Nudge session'}).count(),0);
    if(shots)await home.screenshot({path:path.join(shots,'first-session-starting.png')});
    await home.waitFor({state:'hidden'});
    assert.ok(await page.evaluate(()=>state.firstRun.session===state.captures[0].session));
    // AppKit sends the open tab's physical depth and the usable height below it.
    // Exercise a shrinking native viewport while a bottom-row action holds focus.
    const geometry={width:188,height:38,offset:0,wing:32,pixel:.5,corner:8,rimOffset:3,available:140};
    await cmd('home');
    await page.setViewportSize({width:320,height:178});
    await page.evaluate(m=>updateNotchGeometry(m),geometry);
    const openTerminal=home.getByRole('button',{name:'Open in Terminal'});
    await openTerminal.focus();
    await page.evaluate(()=>updateBounds(true));
    const bounds=await home.evaluate(el=>{
      const rect=el.getBoundingClientRect(),tab=document.querySelector('#islandToggle').getBoundingClientRect();
      const action=document.activeElement.getBoundingClientRect(),layout=sent.findLast(m=>m.type==='layout');
      return {tab:tab.bottom,start:rect.top,end:rect.bottom,action:action.bottom,layout:layout.height,
        scroll:el.scrollHeight>el.clientHeight,windowScrollY:scrollY};
    });
    assert.equal(bounds.tab,geometry.height);assert.equal(bounds.start,bounds.tab);
    assert.ok(bounds.scroll && bounds.end<=178 && bounds.action<=bounds.end && bounds.windowScrollY===0);
    assert.equal(bounds.layout,Math.ceil(bounds.end));
    await page.setViewportSize({width:440,height:760});
    await page.evaluate(m=>updateNotchGeometry({...m,available:700}),geometry);
    await click('Open in Terminal');
    assert.deepEqual(await page.evaluate(()=>sent.findLast(m=>m.type==='focus-session')),{type:'focus-session',id:job.session});
    await page.evaluate(()=>workspaceCommand('live-error','Fixture focus error'));
    assert.ok(await home.isVisible());
    await page.evaluate(id=>workspaceCommand('session-focused',id),job.session);
    assert.ok(await home.isHidden());
