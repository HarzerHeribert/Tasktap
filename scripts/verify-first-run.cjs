    assert.equal(await page.evaluate(()=>sent.some(m=>m.type==='enqueue'||m.type==='dictation-start')),false);
    const folder='/fixture/projects/tapped';
    await page.evaluate(folder=>projectsDiscovered([{folder:'/fixture/projects/ComfyUI',name:'ComfyUI'},{folder,name:'tapped'}]),folder);
