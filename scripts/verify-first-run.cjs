    assert.equal(await firstExample.evaluate(el=>getComputedStyle(el).animationName),'none');
    await composer.pressSequentially('a');
    assert.ok(await examples.isHidden());
    await composer.press('Backspace');
    assert.ok(await examples.isVisible());
    assert.equal(await page.getByRole('button',{name:'Review',exact:true}).isDisabled(),true);
    await page.evaluate(()=>{state.speakRouting=true;state.speak=true;state.voiceEngine='test-voice'});
    await composer.fill('hello');await click('Review');
    await click('Keep typing');await click('Cancel');
