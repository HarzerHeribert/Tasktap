    await cmd('open-app');
    assert.equal(await page.getByRole('button',{name:'Open in Terminal',exact:true}).count(),0);
    const owned={owned:'yes',id:job.session,folder,host:'terminal',inbox:'manual',agent:job.agent,task:job.task,available:'yes',startup:'confirmed',state:'Connected'};
    await page.evaluate(r=>externalSessions([{...r,startup:'pending',state:'Needs input',waitingFor:'Review folder access'}]),owned);
    await home.getByRole('heading',{name:'Claude Code needs input'}).waitFor();
    assert.match(await home.innerText(),/Review folder access/);
    assert.equal(await home.getByRole('button',{name:'Nudge session'}).count(),0);
    await page.evaluate(r=>externalSessions([{...r,id:'another-session',task:'Unrelated work'},r]),owned);
    if(shots)await page.locator('#notch-home').screenshot({path:path.join(shots,'first-session-ready.png')});
    await click('Nudge session');
    await page.getByLabel('Transcript').fill('Which file should I read first?');
    await click('Review capture');
    await page.getByRole('heading',{name:'Review follow-up'}).waitFor();
