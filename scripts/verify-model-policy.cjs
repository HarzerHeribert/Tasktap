const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({state:{}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../prototype/model-policy.js'),'utf8'),context);
const evaluate = code => vm.runInContext(code,context);

assert.equal(evaluate('sessionModelPolicy().adaptive'),false);
assert.equal(evaluate('sessionModelPolicy().defaultAgent'),'claude');
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'a task'}).model"),'');
assert.equal(evaluate("modelPlanFor({mode:'note'})"),null);
evaluate("state.sessionModels={adaptive:true,agents:{codex:{quick:'small',standard:'medium',complex:'large'}}}");
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Fix the spelling in architecture.md'}).model"),'small');
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Implement a reusable capture button'}).model"),'medium');
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Migrate the distributed database with rollback'}).model"),'large');
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Entwickle eine kleine Ansicht'}).model"),'medium');
evaluate("state.sessionModels.standardAt=2;state.sessionModels.complexAt=5");
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Implement a reusable capture button'}).model"),'large');
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Implement a button',modelOverride:{agent:'codex',value:'custom'}}).model"),'custom');
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'claude',brief:'Implement a button',modelOverride:{agent:'codex',value:'custom'}}).model"),'opus');
assert.equal(evaluate("modelPlanFor({mode:'nudge',agent:'codex',brief:'Migrate everything',modelOverride:{agent:'codex',value:'custom'}}).model"),'');
assert.equal(evaluate("modelPlanFor({mode:'nudge',agent:'codex'}).mode"),'existing');
evaluate("state.sessionModels={adaptive:true}");
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Untersuche das Verhalten',modelEstimate:{score:9,evidence:'Untersuche',brief:'Untersuche das Verhalten'}}).score"),9);
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'Different request',modelEstimate:{score:9,brief:'Old request'}}).score"),4);
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'codex',brief:'same',modelEstimate:{score:99,brief:'same'}}).score"),4);
evaluate("state.sessionModels={adaptive:false,agents:{claude:{fixed:'pinned'}}}");
assert.equal(evaluate("modelPlanFor({mode:'ask',agent:'claude',brief:'Migrate every server'}).model"),'pinned');
console.log('Model policy defaults, thresholds, providers, overrides, estimate invalidation, multilingual cues and nudge preservation passed.');
