/* Browser checks for real state semantics, unread focus, motion and safe answers. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE});
 try{
  const page=await browser.newPage({viewport:{width:1360,height:900},reducedMotion:'no-preference'});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.addInitScript(()=>{window.messages=[];window.webkit={messageHandlers:{workspace:{postMessage:m=>messages.push(m)}}}});
  await page.goto(pathToFileURL(path.resolve('prototype/index.html')).href+'#workspace');
  await page.evaluate(async()=>{
   state.firstRun={done:true};state.projects=[{id:'p',folder:'/tmp/attention',name:'Observer workspace',available:true,aliases:[]}];
   state.sessions=['a','b'].map(id=>({id,project:'p',host:'tasktap',agent:id==='a'?'claude':'codex',task:id==='a'?'Active editor':'Background research',interactive:true,managed:true,available:true,state:'Connected',log:[]}));
   state.captures=[];state.decisions=[];state.notes=[];state.alerts=true;
   Object.assign(state.workspaceDeck,{openProjects:['p'],activity:[],seen:{},observerReads:{},layouts:{p:{groups:[{id:'left',tabs:['terminal:a'],active:'terminal:a'},{id:'right',tabs:['terminal:b'],active:'terminal:b'}],selected:0}},background:{}});
   await workspaceDeck.receive([{event:'sessions',sessions:['a','b'].map(id=>({id,cwd:'/tmp/attention',kind:'agent',title:id,running:true}))}]);
   showWorkspace();go('p');
   window.observerSeq={a:0,b:0};window.sendObservation=(id,state,extra={})=>{
    const previous=sessionObservation.get(id)||{};
    return workspaceDeck.receive([{event:'observation',id,observation:{...previous,agent:id==='a'?'claude':'codex',launchId:'launch-'+id,
      sequence:++observerSeq[id],updatedAt:Date.now()/1000,state,isWorking:state==='working',turn:1,event:'activity',activity:'Read',...extra}}]);
   };
   await sendObservation('a','working',{event:'turn_started'});
   await sendObservation('b','working',{event:'turn_started'});
   window.leftTerminal=document.querySelector('[data-session-id="a"] .deck-terminal');
  });
  const pane=id=>page.locator('.deck-group[data-session-id="'+id+'"]');
  await pane('a').locator('.xterm-helper-textarea').focus();
  await page.waitForFunction(()=>document.activeElement?.classList.contains('xterm-helper-textarea'));
  const before=await pane('b').boundingBox();
  assert.equal(await pane('a').evaluate(el=>getComputedStyle(el,'::after').borderTopColor),'rgba(0, 0, 0, 0)','working uses a dot, never a full-pane blue frame');
  await page.evaluate(()=>sendObservation('b','needsPermission',{event:'permission_requested',question:'Permission required for Bash.'}));
  await page.waitForFunction(()=>document.querySelector('[data-session-id="b"]').dataset.sessionState==='permission');
  assert.match(await pane('b').locator('.deck-session-status').innerText(),/Needs permission/);
  assert.match(await pane('b').locator('.deck-question').innerText(),/Respond in this terminal/);
  assert.equal(await page.evaluate(()=>state.decisions.length),0,'native prompts must not manufacture answerable Tasktap decisions');
  assert.equal(await page.locator('#nav [data-workspace="p"]').getAttribute('data-status'),'permission');
  assert.equal(await page.evaluate(()=>{updateSignal();return document.body.dataset.signal}),'waiting');
  assert.equal(await pane('b').evaluate(el=>getComputedStyle(el,'::after').animationIterationCount),'2');
  await page.evaluate(()=>sendObservation('b','working',{event:'continued',question:'',activity:'Bash'}));
  await page.evaluate(()=>sendObservation('b','ready',{event:'turn_finished',finalAnswer:'Existing **answer**\n<script>window.UNSAFE=true</script>',answers:[{turn:1,file:'answer-0001.txt',time:Date.now()/1000}],history:[{kind:'turn_finished',state:'ready',turn:1,at:Date.now()/1000}]}));
  await page.waitForFunction(()=>document.querySelector('[data-session-id="b"]').dataset.sessionState==='complete');
  assert.match(await pane('b').locator('.deck-session-status').innerText(),/Answer ready/);
  assert.equal(await pane('b').locator('.deck-session-ring rect').evaluate(el=>getComputedStyle(el).animationIterationCount),'1');
  await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(()=>sessionObservation.unread('b')),true,'another focused pane cannot acknowledge a result');
  assert.equal(await page.evaluate(()=>state.sessions.find(s=>s.id==='b').state),'Ready','turn completion is not task Complete');
  assert.ok(await page.evaluate(()=>messages.some(m=>m.type==='notify'&&m.kind==='answer'&&m.id==='b:1')));
  const after=await pane('b').boundingBox();assert.deepEqual(after,before,'state overlays never move pane bounds');
  fs.mkdirSync('output/session-attention',{recursive:true});
  await page.screenshot({path:'output/session-attention/answer-ready.png'});
  const count=await page.evaluate(()=>state.workspaceDeck.activity.length);
  await page.evaluate(()=>{const o=sessionObservation.get('b');sessionObservation.receive('b',o);externalSessions([{id:'b',owned:'yes',agent:'codex',host:'tasktap',folder:'/tmp/attention',task:'Background research',available:'yes',state:'Connected',observation:JSON.stringify(o)}])});
  assert.equal(await page.evaluate(()=>state.workspaceDeck.activity.length),count,'duplicate scans do not create more answers');
  assert.equal(await page.evaluate(()=>state.sessions.find(s=>s.id==='b').state),'Ready','transport discovery cannot overwrite observed state');
  await pane('b').locator('.deck-session-status').click();
  assert.match(await page.locator('.observer-details').innerText(),/finished turn does not establish task success/);
  await page.screenshot({path:'output/session-attention/details.png'});
  await page.locator('[data-action="observer-answer"]').click();
  assert.match(await page.locator('.observer-answer-body').innerText(),/Existing answer/);
  assert.equal(await page.evaluate(()=>window.UNSAFE),undefined,'copied answer is rendered as sanitized Markdown');
  await page.evaluate(()=>dismissCard());
  await pane('b').locator('.xterm-helper-textarea').focus();
  await page.waitForFunction(()=>!sessionObservation.unread('b'));
  await page.waitForFunction(()=>document.querySelector('[data-session-id="b"]').dataset.sessionState==='ready');
  assert.equal(await page.evaluate(()=>document.querySelector('[data-session-id="a"] .deck-terminal')===leftTerminal),true,'state changes preserve the PTY view');
  await page.evaluate(()=>sendObservation('a','needsInput',{event:'input_requested',question:'Which option?'}));
  await pane('a').locator('.xterm-helper-textarea').focus();
  assert.equal(await page.evaluate(()=>sessionObservation.cue('a').kind),'input','focusing cannot resolve a pending question');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await pane('a').evaluate(el=>getComputedStyle(el,'::after').animationName),'none');
  await page.evaluate(()=>sendObservation('b','working',{event:'turn_started',turn:2,finalAnswer:undefined}));
  assert.equal(await pane('b').locator('.deck-state-dot').evaluate(el=>getComputedStyle(el).animationName),'none');
  await page.evaluate(()=>sendObservation('b','failed',{event:'turn_failed',error:'Provider unavailable'}));
  await page.waitForFunction(()=>document.querySelector('[data-session-id="b"]').dataset.sessionState==='failure');
  await page.evaluate(()=>sendObservation('b','ended',{event:'process_exited',lastTurnState:'failed',exitCode:1}));
  await page.waitForFunction(()=>document.querySelector('[data-session-id="b"]').dataset.sessionState==='ended');
  assert.equal(await page.evaluate(()=>state.captures.some(c=>c.receipt==='Complete')),false);
  await page.setViewportSize({width:390,height:760});
  await page.evaluate(()=>{const l=state.workspaceDeck.layouts.p;l.focus=true;l.selected=0;render()});
  assert.equal(await page.evaluate(()=>document.querySelector('#workspace-stage').scrollWidth<=document.querySelector('#workspace-stage').clientWidth+2),true);
  await page.setViewportSize({width:1360,height:900});await page.emulateMedia({reducedMotion:'no-preference'});
  await pane('a').locator('.xterm-helper-textarea').focus();
  await page.evaluate(()=>sendObservation('a','ready',{event:'turn_finished',turn:2,question:'',answers:[{turn:2,time:Date.now()/1000,file:'answer-0002.txt'}]}));
  await page.waitForFunction(()=>!sessionObservation.unread('a'));
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.type==='notify'&&m.kind==='answer'&&m.id==='a:2').length),0,'an already focused answer is acknowledged after its sweep without a banner');
  assert.equal(await page.evaluate(()=>{
   const s=sess('b'),old=sessionObservation.get('b');
   s.observation={...old,sequence:old.sequence+1,state:'working'};
   const current=sessionObservation.get('b').state;
   s.observation=old;
   return current;
  }),'working','a newer shared-window snapshot supersedes the local observation cache');
  await page.evaluate(async()=>{state.workspaceDeck.layouts.p.focus=false;render();await sendObservation('a','working',{event:'turn_started',turn:2,question:''});await sendObservation('b','needsPermission',{event:'permission_requested',turn:3,question:'Approve the next command in the terminal.'})});
  await page.waitForTimeout(180);
  fs.mkdirSync('output/session-attention',{recursive:true});
  await page.screenshot({path:'output/session-attention/panes.png'});
  await page.evaluate(()=>{document.body.classList.add('notch-first');homeMode='peek';drawHome()});
  assert.match(await page.locator('#notch-home').innerText(),/Needs permission/);
  assert.deepEqual(errors,[]);
  console.log('PASS: observed states, one-shot rings, exact/safe answers, per-pane acknowledgement, pending prompts, sidebar/notch, duplicate recovery, stable PTYs, reduced motion and narrow layout.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
