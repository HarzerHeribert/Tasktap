// Drive the real wizard and native reply contracts; no login, Keychain or inference required.
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE||undefined});
  try{
    const page=await browser.newPage({viewport:{width:960,height:780},reducedMotion:'reduce'});
    page.setDefaultTimeout(4500);
    await page.addInitScript(()=>{window.sent=[];window.webkit={messageHandlers:{workspace:{postMessage:m=>window.sent.push(m)}}}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(__dirname,'../prototype/index.html')).href+'#workspace');
    const config={choice:'local',workers:{claude:'Claude plan login',codex:'Sign-in needed'},workerHealth:{claude:'signedIn',codex:'signedOut'},
      accounts:[{id:'plan-a',label:'Personal',status:'enabled'},{id:'plan-b',label:'Studio',status:'enabled'}],account:'plan-a',keys:{},models:{codex:'existing-model'},serverProfiles:{},serverKind:'ollama'};
    const recv=(extra={},note='',request='',ok=true,account='')=>page.evaluate(a=>aiConnections.receive(...a),[{...config,...extra},note,!!request,ok,request,account]);
    const click=s=>page.getByRole('button',{name:s,exact:true}).click();
    const next=()=>click('Continue'), back=()=>click('Back'), route=page.locator('#setup-prep-route');
    const read=type=>page.evaluate(t=>sent.filter(x=>x.type===t),type);
    const reopen=async()=>{await page.evaluate(()=>workspaceCommand('run-setup'));await next()};
    const shots=process.env.TASKTAP_SCREENSHOTS;
    const shot=async name=>{if(shots)await page.locator('#modal').screenshot({path:path.join(shots,'prep-'+name+'.png')})};
    await reopen();await page.getByText('Reading your saved connections…').waitFor();
    await recv();assert.equal(await route.inputValue(),'local');
    await route.selectOption('codex');await next();assert.ok(await route.isVisible());
    await click('Sign in to Codex');assert.deepEqual((await read('worker-login')).at(-1),{type:'worker-login',agent:'codex'});
    config.workerHealth.codex='signedIn';config.workers.codex='ChatGPT login';await recv();
    const id=(await read('ai-codex-identity')).at(-1).id;
    await page.evaluate(id=>setupPreparation.identity(id,'studio@example.test · Studio'),id);
    assert.match(await page.locator('#setup-billing').innerText(),/studio@example.test · Studio/);
    assert.ok(!await page.getByText('No Codex account is signed in.',{exact:true}).isVisible());
    await shot('codex');await next();assert.equal(await page.locator('#setup-agent').inputValue(),'claude');
    assert.match(await page.locator('#setup-route-summary').innerText(),/studio@example.test/);
    assert.match(await page.locator('#setup-worker-account').innerText(),/Claude plan login/);
    await shot('handoff');await next();await click('Save settings');
    const save=(await read('ai-save')).at(-1);
    assert.equal(save.route,'codex');assert.equal(save.model,'existing-model');assert.equal(save.agent,undefined);
    await recv({},'Irrelevant reply','a-different-request');
    assert.ok(await page.locator('#setup-wizard').isVisible());
    await recv({},'Can’t save while a capture is being prepared.',save.request,false);
    await route.waitFor();assert.match(await page.locator('.prep-notice').innerText(),/Can’t save/);
    assert.equal(await page.evaluate(()=>state.sessionModels),undefined);
    await route.selectOption('ollama');
    assert.equal(await page.locator('#server-url').inputValue(),'http://localhost:11434/v1');
    await click('Find models');const probe=(await read('ai-model-list')).at(-1);
    assert.equal(probe.key,'');assert.equal(probe.input,undefined);
    await page.evaluate(id=>serverSetup.receive(id,{error:'Start Ollama or check the address.'}),probe.id);
    assert.match(await page.locator('#server-status').innerText(),/Start Ollama/);
    await next();assert.ok(await route.isVisible());
    await page.getByText('API key Optional',{exact:true}).click();await page.locator('#server-key').fill('fixture-secret');
    await click('Find models');await page.evaluate(()=>serverSetup.receive(sent.at(-1).id,{models:['studio:local','studio:cloud']}));
    await page.locator('#ai-model').selectOption('studio:cloud');assert.match(await page.locator('#setup-billing').innerText(),/cloud account/);
    await page.locator('#ai-model').selectOption('studio:local');await shot('ollama');
    await next();await back();assert.equal(await page.locator('#ai-model').inputValue(),'studio:local');
    await next();await page.locator('#setup-agent').selectOption('pi');await next();await click('Save settings');
    const serverSave=(await read('ai-save')).at(-1);
    assert.deepEqual(serverSave.server,{kind:'ollama',url:probe.url,useSaved:false});assert.equal(serverSave.model,'studio:local');assert.equal(serverSave.key,'fixture-secret');
    assert.equal(await page.evaluate(()=>aiConnections.choice()),'local');
    config.choice='server';config.serverProfiles.ollama={model:'studio:local',url:probe.url,hasKey:'yes'};
    await recv({},'Saved.',serverSave.request);
    assert.equal(await page.locator('#setup-wizard').count(),1);assert.ok(!await page.locator('#modal').isVisible());
    assert.equal(await page.evaluate(()=>sessionModelPolicy().defaultAgent),'pi');
    assert.ok(!await page.evaluate(()=>JSON.stringify(localStorage).includes('fixture-secret')));
    await reopen();assert.equal(await route.inputValue(),'ollama');assert.equal(await page.locator('#ai-model').inputValue(),'studio:local');
    await route.selectOption('chatgpt');await page.locator('#setup-plan-account').selectOption('plan-b');assert.match(await page.locator('#setup-billing').innerText(),/Studio/);
    await page.keyboard.press('Escape');assert.equal((await read('ai-account')).length,0);assert.equal((await read('ai-save')).length,2);
    await reopen();await route.selectOption('chatgpt');await page.locator('#setup-plan-account').selectOption('plan-b');
    await next();await next();await click('Save settings');const planSave=(await read('ai-save')).at(-1);
    assert.equal(planSave.account,'plan-b');assert.equal(planSave.route,'chatgpt');await recv({choice:'chatgpt',account:'plan-b'},'Saved.',planSave.request);
    assert.equal((await read('enqueue')).length,0);
    assert.deepEqual(errors,[]);console.log('Wizard preparation: payer, CLI login, server discovery, draft secrets, verified save, retry, cancel and independent worker passed.');
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
