const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE||undefined});
 try{
  const page=await browser.newPage({viewport:{width:1200,height:800}}),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.addInitScript(()=>{window.messages=[];window.webkit={messageHandlers:{workspace:{postMessage:m=>messages.push(m)}}}});
  await page.goto(pathToFileURL(path.resolve('prototype/index.html')).href);
  await page.evaluate(async()=>{
   state.firstRun={done:true};state.alerts=true;state.projects=[{id:'p',name:'Tasktap',folder:'/tmp/background',aliases:[]},{id:'q',name:'Other project',folder:'/tmp/other',aliases:[]}];
   state.sessions=[{id:'agent',project:'p',host:'tasktap',agent:'codex',interactive:true,state:'Running',task:'Fix login redirect',log:[]}];state.decisions=[];state.captures=[];
   Object.assign(state.workspaceDeck,{openProjects:['p','q'],layouts:{},background:{},closedWorkspaces:{},activity:[],seen:{},sidebarHidden:false});
   showWorkspace();go('p');await workspaceDeck.receive([{event:'sessions',sessions:[{id:'agent',cwd:'/tmp/background',title:'Fix login redirect',kind:'agent',running:true},{id:'other',cwd:'/tmp/other',title:'Other shell',kind:'shell',running:true}]}]);
   workspaceDeck.open('terminal:agent','p');
  });
  const tab=page.locator('[data-action="deck-tab"][data-id="terminal:agent"]'),background=page.locator('[data-action="workspace-background"][data-id="agent"]');
  await page.getByRole('button',{name:'Close Fix login redirect view',exact:true}).click();
  assert.equal(await tab.count(),1,'requesting close leaves the process and tab intact');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await tab.count(),1);
  await page.keyboard.press('Meta+w');
  await page.getByRole('button',{name:'Keep running in background',exact:true}).click();
  assert.equal(await tab.count(),0);
  assert.equal(await background.isVisible(),true);
  assert.match(await background.innerText(),/Working/);
  await page.evaluate(()=>workspaceDeck.receive([{event:'focus',id:'agent'}]));
  assert.equal(await tab.count(),0,'a late launcher focus cannot undo an explicit background choice');
  assert.equal(await page.evaluate(()=>messages.some(m=>m.op==='stop'&&m.id==='agent')),false);
  await page.evaluate(()=>{state.decisions=[{id:'question',session:'agent',q:'Which approach?',choices:['A','B']}];render()});
  assert.match(await background.innerText(),/Needs input/);
  await page.getByRole('button',{name:'Collapse background sessions for Tasktap',exact:true}).click();
  assert.equal(await background.isVisible(),false);
  assert.equal(await page.locator('[data-workspace="p"]').getAttribute('data-status'),'input');
  await page.evaluate(()=>{state.decisions=[];workspaceDeck.outcome({session:'agent',state:'Complete',capture:'result',message:'Login fixed'});render()});
  assert.equal(await page.locator('[data-workspace="p"]').getAttribute('data-status'),'complete');
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.type==='notify'&&m.kind==='complete'&&m.id==='result').length),1,'background results notify while the app is focused');
  await page.locator('[data-action="workspace-project"][data-id="p"]').click();
  assert.equal(await page.locator('[data-workspace="p"]').getAttribute('data-status'),'complete','opening a folder does not acknowledge hidden results');
  await page.getByRole('button',{name:'Expand background sessions for Tasktap',exact:true}).click();
  assert.match(await background.innerText(),/Answer ready/);
  await page.screenshot({path:'/tmp/tasktap-background-ready.png'});
  const starts=await page.evaluate(()=>messages.filter(m=>m.op==='start').length);
  await background.click();
  assert.equal(await tab.count(),1);assert.equal(await background.count(),0);
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.op==='start').length),starts,'surfacing attaches instead of spawning');
  assert.ok(await page.evaluate(()=>messages.some(m=>m.op==='attach'&&m.id==='agent')));
  // A failed result remains visible and deduplicated; output alone never claims readiness.
  await page.getByRole('button',{name:'Close Fix login redirect view',exact:true}).click();
  await page.getByRole('button',{name:'Keep running in background',exact:true}).click();
  await page.evaluate(()=>{workspaceDeck.outcome({session:'agent',state:'Failed',capture:'failure',message:'Build failed'});render()});
  assert.match(await background.innerText(),/Failed/);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.nav-background-symbol').first().evaluate(el=>getComputedStyle(el).animationName),'none');
  await page.reload();await page.evaluate(()=>{showWorkspace();go('p')});
  assert.equal(await background.isVisible(),true,'background membership survives relaunch');
  await page.evaluate(()=>workspaceDeck.receive([{event:'sessions',sessions:[{id:'agent',cwd:'/tmp/background',title:'Fix login redirect',kind:'agent',running:true},{id:'hidden',cwd:'/tmp/background',title:'Hidden shell',kind:'shell',running:true},{id:'other',cwd:'/tmp/other',title:'Other shell',kind:'shell',running:true}]}]));
  await page.getByRole('button',{name:'Close Tasktap workspace',exact:true}).click();
  assert.match(await page.locator('#dialog-heading').innerText(),/stop 2 sessions/);
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('[data-workspace="p"]').count(),1);
  await page.getByRole('button',{name:'Close Tasktap workspace',exact:true}).click();
  await page.getByRole('button',{name:'Stop sessions and close',exact:true}).click();
  assert.equal(await page.locator('[data-workspace="p"]').count(),1,'workspace waits for service acknowledgement');
  assert.ok(await page.evaluate(()=>messages.some(m=>m.op==='stop-workspace'&&m.cwd==='/tmp/background')));
  await page.evaluate(()=>workspaceDeck.receive([{event:'error',cwd:'/tmp/background',error:'Could not stop workspace'}]));
  assert.equal(await page.locator('[data-workspace="p"]').count(),1,'a failed stop never hides the workspace');
  await page.getByRole('button',{name:'Close Tasktap workspace',exact:true}).click();
  await page.getByRole('button',{name:'Stop sessions and close',exact:true}).click();
  await page.evaluate(()=>workspaceDeck.receive([{event:'workspace-closed',cwd:'/tmp/background'}]));
  assert.equal(await page.locator('[data-workspace="p"]').count(),0);
  assert.equal(await page.locator('[data-workspace="q"]').count(),1,'closing one workspace preserves another');
  await page.evaluate(()=>workspaceDeck.receive([{event:'session',session:{id:'late',cwd:'/tmp/background',kind:'shell',running:true}}]));
  assert.equal(await page.locator('[data-workspace="p"]').count(),0,'late launches never reopen a closed workspace');
  assert.ok(await page.evaluate(()=>messages.some(m=>m.op==='stop'&&m.id==='late')));
  await page.evaluate(()=>{window.reopenStatus='waiting';workspaceDeck.prepareLaunch('p').then(()=>window.reopenStatus='opened')});
  assert.equal(await page.evaluate(()=>window.reopenStatus),'waiting','a reviewed new task waits for workspace reopen acknowledgement');
  await page.evaluate(()=>workspaceDeck.receive([{event:'workspace-opened',cwd:'/tmp/background'}]));
  assert.equal(await page.evaluate(()=>window.reopenStatus),'opened');
  await page.evaluate(()=>{workspaceDeck.openWorkspace('p');workspaceDeck.open('terminal:agent','p')});
  assert.ok(await page.evaluate(()=>messages.some(m=>m.op==='open-workspace'&&m.cwd==='/tmp/background')));
  // Ended tabs close directly. A pending live launch offers the same deliberate choice.
  await page.evaluate(()=>workspaceDeck.receive([{event:'session',session:{id:'agent',cwd:'/tmp/background',title:'Fix login redirect',kind:'agent',running:false,exit:0}}]));
  await page.getByRole('button',{name:'Close Fix login redirect view',exact:true}).click();
  assert.equal(await page.locator('#modal').isVisible(),false);
  await page.locator('[data-action="deck-terminal"]:visible').first().click();
  const pending=await page.evaluate(()=>messages.filter(m=>m.op==='start').at(-1).id);
  await page.locator('[data-action="deck-close"][data-id="terminal:'+pending+'"]').click();
  await page.getByRole('button',{name:'Keep running in background',exact:true}).click();
  await page.locator('[data-action="workspace-background"][data-id="'+pending+'"]').click();
  assert.equal(await page.locator('[data-action="deck-tab"][data-id="terminal:'+pending+'"]').count(),1,'pending background sessions can be surfaced before launch completes');
  await page.locator('[data-action="deck-close"][data-id="terminal:'+pending+'"]').click();
  await page.getByRole('button',{name:'Stop session',exact:true}).click();
  assert.ok(await page.evaluate(id=>messages.some(m=>m.op==='stop'&&m.id===id),pending));
  assert.equal(await page.locator('[data-action="deck-tab"][data-id="terminal:'+pending+'"]').count(),1,'stopping a panel waits for acknowledgement');
  await page.evaluate(id=>workspaceDeck.receive([{event:'error',id,error:'Could not stop session'}]),pending);
  assert.equal(await page.locator('[data-action="deck-tab"][data-id="terminal:'+pending+'"]').count(),1,'a failed stop preserves the session panel');
  await page.locator('[data-action="deck-close"][data-id="terminal:'+pending+'"]').click();
  await page.getByRole('button',{name:'Stop session',exact:true}).click();
  await page.evaluate(id=>workspaceDeck.receive([{event:'session-cancelled',id}]),pending);
  assert.equal(await page.locator('[data-action="deck-tab"][data-id="terminal:'+pending+'"]').count(),0);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Toggle sidebar',exact:true}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'/tmp/tasktap-background-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: deliberate close/background/stop, sidebar cues, collapsed attention, result alerts, reconnect without spawning, persisted background work, workspace stop acknowledgement/failure, late launches, pending and ended sessions, and mobile layout.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
